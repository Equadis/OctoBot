"""Build chronicle-observed-spells.json from a public Chronicle damage stream.

Inputs: gzip damage stream, a roster JSON mapping caster GUID -> class (taken from the
report's player list), the ability-evidence file and report provenance. Output contains
no GUIDs or character names. Counts are damage HITS, not casts. An observed ID is only
attached to an ability whose key equals the slug of the spell label; everything else is
listed as unmapped for review. Nothing here asserts rank, learn level or coefficients.
"""
import argparse
import gzip
import importlib.util
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("chronicle_casts", HERE / "import-chronicle-casts.py")
chronicle = importlib.util.module_from_spec(spec)
spec.loader.exec_module(chronicle)


# Manual cross-checks against https://octowow.st/db/?spell=<id>, read on 2026-11-22.
# "disputed" means the database names a different spell than the Chronicle label, so the ID is not emitted.
DB = "https://octowow.st/db/?spell="
REVIEWS = {
    ("hunter:steady-shot", 3668): {"verdict": "disputed", "dbName": "zzOLDTrueshot", "dbRank": 5,
                                   "reason": "database names this ID a different spell than the Chronicle label"},
    ("paladin:holy-strike", 10333): {"verdict": "name-matches-deprecated", "dbName": "zzOLDHoly Strike", "dbRank": 8, "dbLevel": 99},
    ("paladin:holy-strike", 10332): {"verdict": "name-matches-deprecated", "dbName": "zzOLDHoly Strike", "dbRank": 7, "dbLevel": 99},
    ("warlock:power-overwhelming", 51714): {"verdict": "name-matches", "dbName": "Power Overwhelming", "dbLevel": 40},
}


def slug(label):
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", label.lower())).strip("-")


def build(players, data, evidence_path, provenance):
    keys = {r["key"] for r in json.loads(Path(evidence_path).read_text())["records"]}
    known = chronicle.load_known_spells(evidence_path)
    report = chronicle.summarise_damage(players, data, known)
    candidates, unmapped, disputed = [], [], []
    for row in report["rows"]:
        if row["status"] != "unmapped":
            continue
        key = f'{row["classId"]}:{slug(row["label"])}'
        entry = {"classId": row["classId"], "spellId": row["spellId"], "label": row["label"],
                 "hits": row["hits"], "distinctCasters": row["distinctCasters"]}
        if key in keys:
            review = REVIEWS.get((key, row["spellId"]))
            if review:
                review = {**review, "source": DB + str(row["spellId"]), "reviewedOn": "2026-11-22"}
            if review and review["verdict"] == "disputed":
                disputed.append({"abilityKey": key, **entry, "review": review})
            else:
                candidates.append({"abilityKey": key, **entry, **({"review": review} if review else {})})
        else:
            unmapped.append(entry)
    return {"schema": "octosim-chronicle-observed-v1", "provenance": provenance,
            "unit": report["unit"],
            "note": "Observation only. Does not establish rank, learn level, coefficients or availability.",
            "observedCandidates": candidates, "disputedObserved": disputed, "unmappedObserved": unmapped}


def write_module(observed, path):
    """Emit the registry-facing module (observed identities; no rank, level or coefficient data)."""
    by_key = {}
    for c in observed["observedCandidates"]:
        by_key.setdefault(c["abilityKey"], []).append(
            {"spellId": c["spellId"], "label": c["label"], "hits": c["hits"], "distinctCasters": c["distinctCasters"],
             **({"dbName": c["review"]["dbName"], "dbRank": c["review"].get("dbRank"), "dbLevel": c["review"].get("dbLevel")} if c.get("review") else {})})
    header = ("// Generated by tools/sim/build-chronicle-observed.py. Observation only: says a spell ID was seen in a\n"
              "// public Chronicle report. Not rank, learn-level or availability evidence; the runtime identity gate accepts these IDs as a spell identity only.\n")
    body = ("export const OBSERVED_SPELLS=" + json.dumps(by_key, separators=(",", ":"), sort_keys=True) + ";\n"
            "export const OBSERVED_PROVENANCE=" + json.dumps(observed["provenance"], separators=(",", ":")) + ";\n")
    Path(path).write_text(header + body, encoding="utf8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("damage", type=Path)
    parser.add_argument("roster", type=Path, help="JSON {guid: CLASS}")
    parser.add_argument("evidence", type=Path)
    parser.add_argument("--report-url", required=True)
    parser.add_argument("--build", required=True)
    parser.add_argument("--realm", required=True)
    parser.add_argument("--date", required=True)
    parser.add_argument("--module-out", type=Path, help="Also write the registry module (observed-spells.mjs)")
    args = parser.parse_args()
    players = {g: {"class": c} for g, c in json.loads(args.roster.read_text()).items()}
    with gzip.open(args.damage, "rb") as stream:
        data = stream.read()
    provenance = {"reportUrl": args.report_url, "clientBuild": args.build, "realm": args.realm,
                  "date": args.date, "stream": "damage"}
    observed = build(players, data, args.evidence, provenance)
    if args.module_out:
        write_module(observed, args.module_out)
    print(json.dumps(observed, indent=1))


if __name__ == "__main__":
    main()
